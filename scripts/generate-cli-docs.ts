#!/usr/bin/env bun
/**
 * Generate `docs/cli.md` from the MAAIDD CLI help output.
 *
 * Deterministic: derived from the actual CLI (`src/cli/index.ts`), not an LLM.
 * Usage:
 *   bun scripts/generate-cli-docs.ts           # write docs/cli.md
 *   bun scripts/generate-cli-docs.ts --check   # exit 1 if stale
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const CLI = join(ROOT, "src", "cli", "index.ts");
const OUT = join(ROOT, "docs", "cli.md");

// Keep in sync with src/cli/app.ts route map.
const COMMANDS = [
  "format",
  "check",
  "metrics",
  "gate",
  "report",
  "mcp",
  "graph",
  "init",
  "completion",
] as const;

function help(args: string[]): string {
  const result = spawnSync("bun", [CLI, ...args, "--help"], {
    cwd: ROOT,
    encoding: "utf8",
    env: { ...process.env, NO_COLOR: "1" },
  });
  const text = `${result.stdout ?? ""}${result.stderr ?? ""}`.trimEnd();
  return text || `(no help output; exit ${result.status})`;
}

function render(): string {
  const parts: string[] = [];
  parts.push("# CLI reference (`maaidd`)");
  parts.push("");
  parts.push(
    "> Generated by `bun scripts/generate-cli-docs.ts` from `src/cli/index.ts`. Do not edit by hand.",
  );
  parts.push("");
  parts.push("## Global usage");
  parts.push("");
  parts.push("```text");
  parts.push(help([]));
  parts.push("```");
  parts.push("");

  for (const cmd of COMMANDS) {
    parts.push(`## \`maaidd ${cmd}\``);
    parts.push("");
    parts.push("```text");
    parts.push(help([cmd]));
    parts.push("```");
    parts.push("");
  }
  return parts.join("\n");
}

const next = render();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== next) {
    process.stderr.write(
      "docs/cli.md is out of date. Run: bun scripts/generate-cli-docs.ts\n",
    );
    process.exit(1);
  }
  process.stdout.write("docs/cli.md is up to date.\n");
} else {
  writeFileSync(OUT, next, "utf8");
  process.stdout.write(`Wrote ${OUT}\n`);
}
